const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const clientsDir = path.join(rootDir, 'clients');
const templatesDir = path.join(rootDir, 'templates');
const partialsDir = path.join(templatesDir, 'partials');

// Parse CLI args: node build.js --client=srilakshmiambulance
function getClientArg() {
  const arg = process.argv.find((a) => a.startsWith('--client=') || a === '-c');
  if (arg && arg.startsWith('--client=')) {
    return arg.split('=')[1].trim();
  }
  const idx = process.argv.indexOf('--client');
  if (idx !== -1 && process.argv[idx + 1]) {
    return process.argv[idx + 1].trim();
  }
  return null;
}

function loadConfig() {
  const clientName = getClientArg();
  let configPath = path.join(rootDir, 'client.config.json');

  if (clientName) {
    const candidate = path.join(clientsDir, clientName.endsWith('.json') ? clientName : `${clientName}.json`);
    if (!fs.existsSync(candidate)) {
      console.error(`[Error] Client profile "${clientName}" not found at: ${candidate}`);
      process.exit(1);
    }
    console.log(`[Config] Using client profile: ${candidate}`);
    // Sync to root client.config.json so it reflects active client
    fs.copyFileSync(candidate, configPath);
  }

  if (!fs.existsSync(configPath)) {
    console.error(`[Error] client.config.json not found in root. Specify --client=<name> or create client.config.json.`);
    process.exit(1);
  }

  const raw = fs.readFileSync(configPath, 'utf8');
  try {
    return JSON.parse(raw);
  } catch (err) {
    console.error(`[Error] Failed to parse JSON in ${configPath}:`, err.message);
    process.exit(1);
  }
}

function renderServices(services) {
  return services.map((s, i) => {
    const delay = i > 0 ? ` style="--reveal-delay:.${(i * 8).toString().padStart(2, '0')}s"` : '';
    return `            <article class="card service-card" data-reveal${delay}>
              <div class="service-media">
                <img src="${s.image}" alt="${s.imageAlt || s.title}" loading="lazy" decoding="async" width="400" height="250" />
              </div>
              <div class="service-content">
                <h3>${s.title}</h3>
                <p>${s.description}</p>
              </div>
            </article>`;
  }).join('\n');
}

function renderServiceAreas(areas) {
  return areas.map((a) => `            <li class="area-item"><span class="area-icon" aria-hidden="true">📍</span><span>${a}</span></li>`).join('\n');
}

function renderGallery(gallery) {
  return gallery.map((item, i) => {
    const delay = i > 0 ? ` style="--reveal-delay:.${(i * 8).toString().padStart(2, '0')}s"` : '';
    return `            <div class="card gallery-card" data-reveal${delay}>
              <div class="gallery-media">
                <img src="${item.src}" alt="${item.alt}" loading="lazy" decoding="async" width="400" height="250" />
              </div>
            </div>`;
  }).join('\n');
}

function renderGSC(tags) {
  if (!tags || !Array.isArray(tags) || !tags.length) return '';
  return tags.map((t) => `    <meta name="google-site-verification" content="${t}" />`).join('\n');
}

function generateThemeCss(config) {
  const c = config.branding.colors;
  const heroImage = config.branding.heroImage || '/assets/img/ambulance-exterior.webp';
  return `:root {
  --brand-red: ${c.brandPrimary || '#e3161c'};
  --brand-red-dark: ${c.brandPrimaryDark || '#b80d16'};
  --brand-red-soft: ${c.brandPrimarySoft || '#fff1f2'};
  --brand-navy: ${c.brandSecondary || '#073b82'};
  --brand-navy-dark: ${c.brandSecondaryDark || '#05295c'};
  --ink: ${c.ink || '#10284c'};
  --muted: ${c.muted || '#39516f'};
  --line: ${c.line || '#e5e7eb'};
  --panel: ${c.panel || '#f8fafc'};
  --white: ${c.white || '#ffffff'};
  --hero-bg-image: url('${heroImage}');
}
`;
}

function generateClientConfigJs(config) {
  const clientData = {
    businessName: config.business.name,
    shortName: config.business.shortName,
    primaryPhone: config.contact.primaryPhone,
    primaryPhoneRaw: config.contact.primaryPhoneRaw,
    secondaryPhone: config.contact.secondaryPhone || null,
    secondaryPhoneRaw: config.contact.secondaryPhoneRaw || null,
    whatsappNumber: config.contact.whatsappNumber,
    whatsappPrefill: config.contact.whatsappPrefill,
    email: config.contact.email,
    address: config.contact.address.full,
    operatingHours: config.business.operatingHours
  };
  return `// Automatically generated by scripts/build.js - DO NOT EDIT DIRECTLY
window.CLIENT_CONFIG = ${JSON.stringify(clientData, null, 2)};
`;
}

function build() {
  console.log('----------------------------------------------------');
  console.log('   Ambulance Multi-Client Site Generator (v1.0.0)    ');
  console.log('----------------------------------------------------');
  const startTime = Date.now();
  const config = loadConfig();
  console.log(`[Build] Client: "${config.business.name}" (${config.id})`);

  // Ensure assets subdirs exist
  fs.mkdirSync(path.join(rootDir, 'assets', 'css'), { recursive: true });
  fs.mkdirSync(path.join(rootDir, 'assets', 'js'), { recursive: true });

  // 1. Generate theme.css
  const themeCss = generateThemeCss(config);
  fs.writeFileSync(path.join(rootDir, 'assets', 'css', 'theme.css'), themeCss, 'utf8');
  console.log('[Write] assets/css/theme.css');

  // 2. Generate client-config.js
  const clientConfigJs = generateClientConfigJs(config);
  fs.writeFileSync(path.join(rootDir, 'assets', 'js', 'client-config.js'), clientConfigJs, 'utf8');
  console.log('[Write] assets/js/client-config.js');

  // Load partials
  const headPartial = fs.readFileSync(path.join(partialsDir, 'head.html'), 'utf8');
  const headerPartial = fs.readFileSync(path.join(partialsDir, 'header.html'), 'utf8');
  const footerPartial = fs.readFileSync(path.join(partialsDir, 'footer.html'), 'utf8');
  const callbarPartial = fs.readFileSync(path.join(partialsDir, 'mobile-callbar.html'), 'utf8');

  // Build JSON-LD Schema
  const schemaObj = {
    "@context": "https://schema.org",
    "@type": ["EmergencyService", "LocalBusiness"],
    "name": config.business.name,
    "alternateName": `${config.business.name} ${config.contact.address.locality}`,
    "telephone": config.contact.primaryPhoneRaw,
    "email": config.contact.email,
    "description": config.seo.home.description,
    "address": {
      "@type": "PostalAddress",
      "streetAddress": config.contact.address.street,
      "addressLocality": config.contact.address.locality,
      "addressRegion": config.contact.address.region,
      "addressCountry": config.contact.address.country || "IN",
      "postalCode": config.contact.address.postalCode
    },
    "geo": {
      "@type": "GeoCoordinates",
      "latitude": config.contact.geo.latitude,
      "longitude": config.contact.geo.longitude
    },
    "areaServed": config.serviceAreas,
    "aggregateRating": {
      "@type": "AggregateRating",
      "ratingValue": config.business.rating,
      "reviewCount": config.business.reviewCount
    },
    "openingHoursSpecification": [{
      "@type": "OpeningHoursSpecification",
      "dayOfWeek": ["Monday","Tuesday","Wednesday","Thursday","Friday","Saturday","Sunday"],
      "opens": "00:00",
      "closes": "23:59"
    }],
    "url": `${config.seo.domain}/`
  };
  const schemaJsonLd = JSON.stringify(schemaObj, null, 8);

  const sharedTokens = {
    '{{BUSINESS_NAME}}': config.business.name,
    '{{SHORT_NAME}}': config.business.shortName || config.business.name,
    '{{TAGLINE}}': config.business.tagline,
    '{{HERO_EYEBROW}}': config.business.heroEyebrow,
    '{{HERO_TITLE}}': config.business.heroTitle,
    '{{HERO_COPY}}': config.business.heroCopy,
    '{{REGIONAL_NOTE}}': config.business.regionalNote,
    '{{OPERATING_HOURS}}': config.business.operatingHours,
    '{{RATING}}': config.business.rating,
    '{{REVIEW_COUNT}}': config.business.reviewCount,
    '{{REVIEW_PLATFORM}}': config.business.reviewPlatform,
    '{{PRIMARY_PHONE}}': config.contact.primaryPhone,
    '{{PRIMARY_PHONE_RAW}}': config.contact.primaryPhoneRaw,
    '{{SECONDARY_PHONE}}': config.contact.secondaryPhone || '',
    '{{SECONDARY_PHONE_RAW}}': config.contact.secondaryPhoneRaw || '',
    '{{WHATSAPP_NUMBER}}': config.contact.whatsappNumber.replace(/[^0-9]/g, ''),
    '{{WHATSAPP_PREFILL_ENCODED}}': encodeURIComponent(config.contact.whatsappPrefill || ''),
    '{{EMAIL}}': config.contact.email,
    '{{STREET_ADDRESS}}': config.contact.address.street,
    '{{LOCALITY}}': config.contact.address.locality,
    '{{REGION}}': config.contact.address.region,
    '{{STATE}}': config.contact.address.state,
    '{{POSTAL_CODE}}': config.contact.address.postalCode,
    '{{FULL_ADDRESS}}': config.contact.address.full,
    '{{GOOGLE_MAPS_URL}}': config.contact.googleMapsUrl,
    '{{LOGO_SRC}}': config.branding.logo.src,
    '{{LOGO_ALT}}': config.branding.logo.alt,
    '{{LOGO_WIDTH}}': config.branding.logo.width || 74,
    '{{LOGO_HEIGHT}}': config.branding.logo.height || 54,
    '{{THEME_COLOR}}': config.branding.themeColor || '#e3161c',
    '{{DOMAIN}}': config.seo.domain,
    '{{GOOGLE_SITE_VERIFICATION_TAGS}}': renderGSC(config.seo.googleSiteVerification),
    '{{GOOGLE_ADS_ID}}': config.integrations.googleAdsId || '',
    '{{GOOGLE_ADS_LABEL}}': config.integrations.googleAdsLabel || '',
    '{{GA4_ID}}': config.integrations.ga4Id || '',
    '{{WEB3FORMS_KEY}}': config.integrations.web3formsKey || 'YOUR_WEB3FORMS_KEY',
    '{{CURRENT_YEAR}}': new Date().getFullYear().toString(),
    '{{CURRENT_DATE}}': new Date().toISOString().split('T')[0],
    '{{SCHEMA_JSON_LD}}': schemaJsonLd,
    '{{SERVICES_GRID_CARDS}}': renderServices(config.services),
    '{{SERVICE_AREAS_ITEMS}}': renderServiceAreas(config.serviceAreas),
    '{{GALLERY_GRID_CARDS}}': renderGallery(config.gallery),
    '{{SECONDARY_PHONE_LINE}}': config.contact.secondaryPhone
      ? `            <p><strong>Secondary:</strong> <a href="tel:${config.contact.secondaryPhoneRaw}">${config.contact.secondaryPhone}</a></p>`
      : '',
    '{{SECONDARY_PHONE_CONTACT_LINK}}': config.contact.secondaryPhone
      ? `                <a href="tel:${config.contact.secondaryPhoneRaw}">${config.contact.secondaryPhone}</a>`
      : '',
    '{{SERVICES_PAGE_H1}}': config.seo.services.h1 || `Emergency Ambulance Services in ${config.contact.address.locality}`
  };

  function applyTokens(str, tokens) {
    let result = str;
    for (const [key, val] of Object.entries(tokens)) {
      result = result.split(key).join(val !== undefined && val !== null ? String(val) : '');
    }
    return result;
  }

  // Compile Pages
  const pages = [
    {
      template: 'index.html',
      output: 'index.html',
      activeNav: 'home',
      seo: config.seo.home,
      canonical: `${config.seo.domain}/`,
      ogImage: config.branding.ogImage || `${config.seo.domain}/assets/img/ambulance-exterior.jpg`,
      robots: 'index,follow'
    },
    {
      template: 'about.html',
      output: 'about.html',
      activeNav: 'about',
      seo: config.seo.about,
      canonical: `${config.seo.domain}/about`,
      ogImage: `${config.seo.domain}/assets/img/ambulance-team.jpg`,
      robots: 'index,follow'
    },
    {
      template: 'services.html',
      output: 'services.html',
      activeNav: 'services',
      seo: config.seo.services,
      canonical: `${config.seo.domain}/services`,
      ogImage: `${config.seo.domain}/assets/img/patient-transfer.jpg`,
      robots: 'index,follow'
    },
    {
      template: 'contact.html',
      output: 'contact.html',
      activeNav: 'contact',
      seo: config.seo.contact,
      canonical: `${config.seo.domain}/contact`,
      ogImage: `${config.seo.domain}/assets/img/ambulance-exterior.jpg`,
      robots: 'index,follow'
    },
    {
      template: '404.html',
      output: '404.html',
      activeNav: '',
      seo: { title: `Page not found | ${config.business.name}`, description: '' },
      canonical: `${config.seo.domain}/404`,
      ogImage: '',
      robots: 'noindex'
    }
  ];

  for (const page of pages) {
    const rawTemplate = fs.readFileSync(path.join(templatesDir, page.template), 'utf8');

    // Build specific page tokens
    const pageTokens = {
      ...sharedTokens,
      '{{PAGE_TITLE}}': page.seo.title,
      '{{PAGE_DESCRIPTION}}': page.seo.description,
      '{{PAGE_ROBOTS}}': page.robots,
      '{{CANONICAL_URL}}': page.canonical,
      '{{OG_TITLE}}': page.seo.title,
      '{{OG_DESCRIPTION}}': page.seo.description,
      '{{OG_IMAGE}}': page.ogImage,
      '{{NAV_ACTIVE_HOME}}': page.activeNav === 'home' ? ' aria-current="page"' : '',
      '{{NAV_ACTIVE_ABOUT}}': page.activeNav === 'about' ? ' aria-current="page"' : '',
      '{{NAV_ACTIVE_SERVICES}}': page.activeNav === 'services' ? ' aria-current="page"' : '',
      '{{NAV_ACTIVE_CONTACT}}': page.activeNav === 'contact' ? ' aria-current="page"' : '',
    };

    // Render partials with pageTokens
    const renderedHead = applyTokens(headPartial, pageTokens);
    const renderedHeader = applyTokens(headerPartial, pageTokens);
    const renderedFooter = applyTokens(footerPartial, pageTokens);
    const renderedCallbar = applyTokens(callbarPartial, pageTokens);

    const fullTokens = {
      ...pageTokens,
      '{{PARTIAL_HEAD}}': renderedHead,
      '{{PARTIAL_HEADER}}': renderedHeader,
      '{{PARTIAL_FOOTER}}': renderedFooter,
      '{{PARTIAL_MOBILE_CALLBAR}}': renderedCallbar
    };

    const finalHtml = applyTokens(rawTemplate, fullTokens);
    fs.writeFileSync(path.join(rootDir, page.output), finalHtml, 'utf8');
    console.log(`[Write] ${page.output}`);
  }

  // Compile Static Config Files
  const metaFiles = ['sitemap.xml', 'robots.txt', 'site.webmanifest'];
  for (const f of metaFiles) {
    const raw = fs.readFileSync(path.join(templatesDir, f), 'utf8');
    const rendered = applyTokens(raw, sharedTokens);
    fs.writeFileSync(path.join(rootDir, f), rendered, 'utf8');
    console.log(`[Write] ${f}`);
  }

  const duration = Date.now() - startTime;
  console.log(`[Success] Template build completed in ${duration}ms!`);
  console.log('----------------------------------------------------');
}

build();
